"""Brings the Android app's translations (lib/i18n.dart) to the light TV app (not part of the app).

Writes the list of languages and the English keys into tvlite/js/i18n.js (between its "generated"
marks) and one file per language, tvlite/js/lang/<code>.js, with the texts in the same order.
index.html loads only the file of the language in use. Run after changing lib/i18n.dart:

    python3 tvlite/tools/make_i18n.py
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DART = os.path.join(ROOT, 'lib', 'i18n.dart')
JS = os.path.join(ROOT, 'tvlite', 'js', 'i18n.js')
LANG_DIR = os.path.join(ROOT, 'tvlite', 'js', 'lang')
INDEX = os.path.join(ROOT, 'tvlite', 'index.html')

STR = r"'((?:[^'\\]|\\.)*)'"


def unescape(s):
    return re.sub(r'\\(.)', lambda m: {'n': '\n', 't': '\t'}.get(m.group(1), m.group(1)), s)


def js(v):
    # JSON is JavaScript, but for the two line separators JavaScript does not allow in strings.
    return json.dumps(v, ensure_ascii=False).replace('\u2028', '\\u2028').replace('\u2029', '\\u2029')


def main():
    src = open(DART, encoding='utf-8').read()
    langs = re.findall(r"\(\s*%s\s*,\s*%s\s*,\s*%s\s*\)" % (STR, STR, STR),
                       src[src.index('kLanguages'):src.index('const List<String> _keys')])
    langs = [[unescape(a), unescape(b), unescape(c)] for a, b, c in langs]
    keys_src = src[src.index('const List<String> _keys = ['):src.index('const Map<String, List<String>> _table')]
    keys = [unescape(k) for k in re.findall(r"^\s*%s,\s*$" % STR, keys_src, re.M)]
    table_src = src[src.index('const Map<String, List<String>> _table'):src.index('final Map<String, int> _index')]
    blocks = re.split(r"^  '(\w+)': \[\s*$", table_src, flags=re.M)
    rows = {}
    for i in range(1, len(blocks), 2):
        code, body = blocks[i], blocks[i + 1]
        body = body[:body.index('\n  ],')]
        rows[code] = [unescape(s) for s in re.findall(r"^\s*%s,\s*$" % STR, body, re.M)]
    bad = [c for c, r in rows.items() if len(r) != len(keys)]
    if bad:
        sys.exit('rows of another length than the keys: %s' % ', '.join(bad))
    codes = [l[0] for l in langs]
    if sorted(rows) != sorted(c for c in codes if c != 'en'):
        sys.exit('the languages and the table do not match')

    text = open(JS, encoding='utf-8').read()
    a, b = '/* <generated by tvlite/tools/make_i18n.py> */', '/* </generated by tvlite/tools/make_i18n.py> */'
    gen = '%s\n  I18N.langs = %s;\n  I18N.keys = %s;\n  %s' % (a, js(langs), js(keys), b)
    text = text[:text.index(a)] + gen + text[text.index(b) + len(b):]
    open(JS, 'w', encoding='utf-8').write(text)

    os.makedirs(LANG_DIR, exist_ok=True)
    for code in sorted(rows):
        name = [l for l in langs if l[0] == code][0]
        body = ('/* %s (%s): the texts of js/i18n.js (I18N.keys) in this language. Written by\n'
                ' * tvlite/tools/make_i18n.py from the Android app\'s lib/i18n.dart. */\n'
                'I18N.add(%s, %s);\n') % (name[1], name[2], js(code), js(rows[code]))
        open(os.path.join(LANG_DIR, code + '.js'), 'w', encoding='utf-8').write(body)

    # index.html loads the file of the language in use: it needs the list of codes.
    html = open(INDEX, encoding='utf-8').read()
    m = re.search(r"var LANGS = '[^']*';", html)
    if not m:
        sys.exit('index.html: no LANGS line')
    html = html[:m.start()] + "var LANGS = '%s';" % ' '.join(sorted(rows)) + html[m.end():]
    open(INDEX, 'w', encoding='utf-8').write(html)
    print('%d texts, %d languages: %s' % (len(keys), len(rows), ' '.join(sorted(rows))))


if __name__ == '__main__':
    main()
