/// The language in use: the customer's choice, or the TV's own language when that is one of ours,
/// otherwise English.
String get currentLanguage {
  final chosen = Store.uiLanguage;
  if (chosen != 'auto') return chosen;
  final tv = WidgetsBinding.instance.platformDispatcher.locale.languageCode.toLowerCase();
  if (tv == 'en' || _table.containsKey(tv)) return tv;
  return 'en';
}

/// The text in the app's language (English when there is no translation for it).
String t(String english) {
  final lang = currentLanguage;
  if (lang == 'en') return english;
  final i = _index[english];
  final row = _table[lang];
  if (i == null || row == null) return english;
  return row[i];
}
